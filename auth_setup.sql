-- ---------------------------------------------------------------------
-- Password hashing helper
-- ---------------------------------------------------------------------
create or replace function hash_datamind_password(p_password text)
returns text
language sql
security definer
set search_path = public, extensions
as $$
  select crypt(p_password, gen_salt('bf'));
$$;

revoke all on function hash_datamind_password(text) from public, anon, authenticated;
grant execute on function hash_datamind_password(text) to service_role;

-- ---------------------------------------------------------------------
-- Role-specific login verification
-- ---------------------------------------------------------------------
create or replace function verify_owner_login(p_username text, p_password text)
returns boolean
language plpgsql
security definer
set search_path = public, extensions
as $$
declare v_match boolean;
begin
  select exists (
    select 1 from owner_users
    where username = p_username
      and is_active = true
      and password_hash = crypt(p_password, password_hash)
  ) into v_match;
  return v_match;
end;
$$;

revoke all on function verify_owner_login(text, text) from public, anon, authenticated;
grant execute on function verify_owner_login(text, text) to service_role;

